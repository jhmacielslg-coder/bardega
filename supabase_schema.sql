-- 1. TABELA DE CATEGORIAS
CREATE TABLE IF NOT EXISTS public.categories (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    icon TEXT DEFAULT '🍢',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Habilitar RLS em categorias
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;

-- Políticas de RLS para categorias
CREATE POLICY "Leitura pública de categorias"
    ON public.categories FOR SELECT
    USING (true);

CREATE POLICY "Admin pode inserir categorias"
    ON public.categories FOR INSERT
    WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Admin pode atualizar categorias"
    ON public.categories FOR UPDATE
    USING (auth.role() = 'authenticated');

CREATE POLICY "Admin pode excluir categorias"
    ON public.categories FOR DELETE
    USING (auth.role() = 'authenticated');


-- 2. TABELA DE PRODUTOS / ITENS DO CARDÁPIO
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    description TEXT,
    image_url TEXT,
    badge TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Habilitar RLS em produtos
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- Políticas de RLS para produtos
CREATE POLICY "Leitura pública de produtos"
    ON public.products FOR SELECT
    USING (true);

CREATE POLICY "Admin pode inserir produtos"
    ON public.products FOR INSERT
    WITH CHECK (auth.role() = 'authenticated');

CREATE POLICY "Admin pode atualizar produtos"
    ON public.products FOR UPDATE
    USING (auth.role() = 'authenticated');

CREATE POLICY "Admin pode excluir produtos"
    ON public.products FOR DELETE
    USING (auth.role() = 'authenticated');


-- 3. TABELA DE CONFIGURAÇÕES DA LOJA (LOGO, NOME, ENDEREÇO)
CREATE TABLE IF NOT EXISTS public.store_settings (
    id TEXT PRIMARY KEY DEFAULT 'main',
    store_name TEXT DEFAULT 'Espetinho Amor de Mãe',
    logo_url TEXT,
    address TEXT,
    whatsapp TEXT,
    delivery_fee NUMERIC(10, 2) DEFAULT 6.00,
    delivery_time TEXT DEFAULT '35–50 min',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.store_settings ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Leitura pública das configurações"
    ON public.store_settings FOR SELECT
    USING (true);

CREATE POLICY "Admin pode atualizar configurações"
    ON public.store_settings FOR ALL
    USING (auth.role() = 'authenticated');


-- 4. BUCKET DE ARMAZENAMENTO PARA FOTOS (STORAGE)
-- Para habilitar no Storage do Supabase:
-- Crie um bucket chamado 'cardapio' e marque como público (Public bucket).
-- Ou execute o comando abaixo caso a extensão de storage esteja disponível:
INSERT INTO storage.buckets (id, name, public)
VALUES ('cardapio', 'cardapio', true)
ON CONFLICT (id) DO NOTHING;

-- Políticas de Storage para o bucket 'cardapio'
CREATE POLICY "Acesso público às imagens do cardápio"
    ON storage.objects FOR SELECT
    USING (bucket_id = 'cardapio');

CREATE POLICY "Admin pode fazer upload de fotos no cardápio"
    ON storage.objects FOR INSERT
    WITH CHECK (bucket_id = 'cardapio' AND auth.role() = 'authenticated');

CREATE POLICY "Admin pode atualizar/deletar fotos do cardápio"
    ON storage.objects FOR DELETE
    USING (bucket_id = 'cardapio' AND auth.role() = 'authenticated');


